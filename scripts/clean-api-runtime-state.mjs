#!/usr/bin/env node
/**
 * Keeps the endpoint's runtime state out of the build.
 *
 *     (runs automatically after `next build`, via `npm run build`)
 *
 * `public/` is copied verbatim into `out/`, and the enquiry endpoint writes into
 * `public/api/data/` and `public/api/logs/` while it runs — rate-limit counters,
 * a reference counter, and `submissions.log`, which records every enquiry
 * including the visitor's name, email, phone and message.
 *
 * So any local test run leaves those files lying in `public/`, and the next
 * build copies them into the folder that gets uploaded. That silently publishes
 * your test data (or, worse, real enquiries) as static files.
 *
 * The directories are meant to be created by the endpoint on the host itself,
 * which is also what makes them writable there. This deletes the generated
 * contents from `out/` after every build, and keeps the two `.htaccess` files
 * that the code writes, so the uploaded tree still carries its own protection.
 *
 * It never touches `public/` itself: the local server needs its state to keep
 * working between builds.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outApi = path.join(root, "out", "api");

/** Written by the endpoint while it serves requests. */
const RUNTIME_DIRS = ["data", "logs"];

if (!fs.existsSync(outApi)) {
  // Nothing to clean: the endpoint was not part of this build.
  process.exit(0);
}

const removed = [];

for (const name of RUNTIME_DIRS) {
  const dir = path.join(outApi, name);
  if (!fs.existsSync(dir)) continue;

  for (const entry of fs.readdirSync(dir)) {
    // The .htaccess files are part of the design: they keep the directory
    // private on Apache hosts and are regenerated by the endpoint anyway.
    if (entry === ".htaccess") continue;

    const target = path.join(dir, entry);
    fs.rmSync(target, { recursive: true, force: true });
    removed.push(`api/${name}/${entry}`);
  }
}

if (removed.length > 0) {
  console.log(
    `clean-api-runtime-state: kept ${removed.length} generated file(s) out of the build`
  );
  for (const file of removed) console.log(`  skipped ${file}`);
}
